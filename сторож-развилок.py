#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сторож развилок: родитель обязан знать каждую языковую папку, которая
лежит под ним — и уводить в неё, а не просто упоминать её.

ПОВОД. Замер 05.10.2026 на `timer-app/`: десять переведённых папок
(ar de en es fr it ja pt-br ru uk), а в трёх развилках — `index.html`,
`privacy.html`, `support.html` — стояло по три языка: uk, ru, en.
Немец, японец и арабский читатель открывали АНГЛИЙСКУЮ политику при
готовой своей, и адрес этой развилки зашит в App Store Connect и в
`Shared/AppInfo.swift`. Страницы внутри папок при этом несли по
одиннадцать `hreflang` и переключатель на десять языков: дети знали
десять, родитель три. Полнота папок и достижимость — разные вещи,
и снаружи они выглядят одинаково (`curl` отдаёт 200 на все десять).

ПОЧЕМУ СКРИПТ ЗАПУСКАЕТСЯ, А НЕ ЧИТАЕТСЯ. Первая редакция этого
сторожа искала в развилке строки вида `"uk/privacy.html"` — и назвала
находкой РОВНО ПОЧИНЕННУЮ страницу: после правки адрес собирается
из таблицы (`langs[j][1] + "/privacy.html"`), литерала больше нет.
Три развилки в репозитории написаны тремя разными способами — цепочкой
`if`, массивом `known`, таблицей пар, — и текстовый разбор меряет форму
записи вместо поведения. Поэтому скрипт развилки ИСПОЛНЯЕТСЯ в node
с подставленными `navigator` и `location`, по одному языку за раз,
и сторож смотрит, куда он увёл. Заодно это ловит то, чего чтение
не поймало бы никогда: ветка есть, а отдаёт не ту папку.

ЧТО ПРОВЕРЯЕТСЯ — три вещи против папок на диске:
  1. поведение редиректа: каждый язык обязан приехать в свою папку,
     незнакомый — в `en` (и приехать хоть куда-то: `null` значит,
     что человек остался на развилке);
  2. `<link rel="alternate" hreflang=…>` — иначе язык теряется для поиска;
  3. ссылки переключателя в теле — иначе язык теряется для того,
     у кого выключен JavaScript.

ЧЕГО СТОРОЖ НЕ ЗНАЕТ — напечатано последней строкой и не живёт
ни в чьей памяти.

    python3 сторож-развилок.py          # код 0 — все развилки полны
"""

import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

КОРЕНЬ = pathlib.Path(__file__).resolve().parent
СТРАНИЦЫ = ("index.html", "privacy.html", "support.html")

# Папка на диске → код в `hreflang`. Соответствие явное: папка `pt-br`
# и код `pt-BR` — разные строки, и угадывать регистр значит однажды
# объявить расхождение, которого нет.
КОД_HREFLANG = {"pt-br": "pt-BR"}

# Папка → теги, с которыми приходят живые телефоны. Региональные варианты
# обязательны: `navigator.languages` почти никогда не отдаёт чистое «de».
ТЕГИ = {
    "en": ["en", "en-US", "en-GB"],
    "ru": ["ru", "ru-RU"],
    "uk": ["uk", "uk-UA"],
    "de": ["de", "de-DE", "de-AT"],
    "es": ["es", "es-ES", "es-MX", "es-419"],
    "fr": ["fr", "fr-FR", "fr-CA"],
    "it": ["it", "it-IT"],
    "ja": ["ja", "ja-JP"],
    "pt-br": ["pt-BR", "pt", "pt-PT"],
    "ar": ["ar", "ar-SA", "ar-EG"],
}

# Языки, которых у нас нет ни у одного приложения. Они обязаны приезжать
# в `en` — это и проверка запасного пути, и контроль самой оснастки:
# если бы подстановка `navigator` не работала, здесь был бы не «en»,
# а `null`, и молчание сторожа читалось бы как «всё хорошо».
ЧУЖИЕ = ["nl-NL", "zh-CN", "ko-KR", "tr-TR"]

ОСНАСТКА = r"""
const fs = require("fs");
const [, , путь, тегиJSON] = process.argv;
const исходник = fs.readFileSync(путь, "utf8");
const теги = JSON.parse(тегиJSON);
const итог = {};
for (const тег of теги) {
  let куда = null;
  Object.defineProperty(globalThis, "navigator", {
    value: { languages: [тег], language: тег },
    configurable: true,
    writable: true,
  });
  Object.defineProperty(globalThis, "location", {
    value: { replace: (u) => { if (куда === null) куда = String(u); } },
    configurable: true,
    writable: true,
  });
  try {
    new Function(исходник)();
  } catch (e) {
    итог[тег] = "ОШИБКА: " + e.message;
    continue;
  }
  итог[тег] = куда;
}
process.stdout.write(JSON.stringify(итог));
"""


def код(папка: str) -> str:
    return КОД_HREFLANG.get(папка, папка)


def языковые_папки(приложение: pathlib.Path, страница: str) -> set:
    """Папки, где эта страница действительно лежит файлом."""
    return {
        п.name
        for п in приложение.iterdir()
        if п.is_dir() and (п / страница).is_file()
    }


def куда_уводит(скрипт: str, теги: list, оснастка: pathlib.Path) -> dict:
    with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False,
                                     encoding="utf-8") as ф:
        ф.write(скрипт)
        путь = ф.name
    try:
        вывод = subprocess.run(
            ["node", str(оснастка), путь, json.dumps(теги)],
            capture_output=True, text=True, check=True,
        )
    finally:
        pathlib.Path(путь).unlink(missing_ok=True)
    return json.loads(вывод.stdout)


def main() -> int:
    if shutil.which("node") is None:
        print("✗ node не найден — поведение развилки проверить нечем. "
              "Это отказ инструмента, а не чистый результат")
        return 2

    with tempfile.TemporaryDirectory() as каталог:
        оснастка = pathlib.Path(каталог) / "оснастка.js"
        оснастка.write_text(ОСНАСТКА, encoding="utf-8")

        осмотрено = 0
        проверок = 0
        находки = []
        без_развилки = []

        for приложение in sorted(p for p in КОРЕНЬ.iterdir() if p.is_dir()):
            if приложение.name.startswith("."):
                continue
            for страница in СТРАНИЦЫ:
                развилка = приложение / страница
                if not развилка.is_file():
                    # Папки с переводом есть, а родителя нет: адрес без языка
                    # отдаёт 404. Для Timer это было бы отказом по 5.1.1,
                    # но у соседа адрес в карточке может вести прямо в папку.
                    # Поэтому это вопрос владельцу, а не вердикт — код
                    # возврата от этого не краснеет.
                    if языковые_папки(приложение, страница):
                        без_развилки.append(f"{приложение.name}/{страница}")
                    continue
                папки = языковые_папки(приложение, страница)
                if not папки:
                    # Страница без языковых папок — не развилка, а сама
                    # страница: так выглядят `en/`, `ru/` в корне сайта.
                    continue
                осмотрено += 1
                строка = f"{приложение.name}/{страница}"
                текст = развилка.read_text(encoding="utf-8")
                голова, _, тело = текст.partition("</head>")

                скрипты = re.findall(r"<script>(.*?)</script>", голова, re.S)
                if not скрипты:
                    находки.append(f"{строка}: развилки нет вовсе — "
                                   f"ни одного <script> в <head>")
                    continue

                теги = []
                ждём = {}
                for папка in sorted(папки):
                    for тег in ТЕГИ.get(папка, [папка]):
                        теги.append(тег)
                        ждём[тег] = f"{папка}/{страница}"
                for тег in ЧУЖИЕ:
                    теги.append(тег)
                    ждём[тег] = f"en/{страница}"

                приехало = куда_уводит("\n".join(скрипты), теги, оснастка)
                промахи = []
                for тег in теги:
                    проверок += 1
                    было = приехало.get(тег)
                    if было != ждём[тег]:
                        промахи.append(f"{тег} → {было!r}, а не {ждём[тег]!r}")
                if промахи:
                    for п in промахи:
                        находки.append(f"{строка}: редирект {п}")

                hreflang = {
                    м.lower()
                    for м in re.findall(r'hreflang="([^"]+)"', голова)
                    if м.lower() != "x-default"
                }
                ссылки = {
                    м.lower()
                    for м in re.findall(
                        r'href="([A-Za-z-]+)/' + re.escape(страница), тело)
                }
                for имя, есть, надо in (
                    ("hreflang", hreflang, {код(п).lower() for п in папки}),
                    ("переключатель", ссылки, папки),
                ):
                    проверок += 1
                    нет = sorted(надо - есть)
                    лишнее = sorted(есть - надо)
                    if нет:
                        находки.append(f"{строка}: в {имя} нет папок {нет}")
                    if лишнее:
                        находки.append(
                            f"{строка}: {имя} зовёт то, чего на диске нет {лишнее}")

                print(f"{строка:28} папок {len(папки):2} · "
                      f"редирект {len(теги) - len(промахи)}/{len(теги)} · "
                      f"hreflang {len(hreflang):2} · ссылок {len(ссылки):2}")

    print()
    if осмотрено == 0 or проверок == 0:
        print("✗ осмотрено ноль развилок — сторож смотрел не туда, "
              "и молчание здесь ничего не значит")
        return 2

    for ф in находки:
        print(f"✗ {ф}")
    print(f"{'✗' if находки else '✓'} развилок {осмотрено}, "
          f"проверок {проверок}, находок {len(находки)}")

    if без_развилки:
        print()
        print("⚠ переводы есть, развилки нет — адрес без языка отдаёт 404:")
        for ф in без_развилки:
            print(f"    {ф}")
        print("  Это вопрос владельцу папки, а не вердикт: адрес в карточке")
        print("  App Store может вести прямо в `en/`. Код возврата не красим.")

    print()
    print("Границы этого сторожа:")
    print("  · он не знает, переведена ли страница в папке: файл на месте —")
    print("    значит язык достижим, а не значит, что он на этом языке;")
    print("  · он сравнивает диск с развилкой и молчит о языке, которого")
    print("    нет нигде: приложение на одиннадцати языках при десяти")
    print("    папках для него выглядит целым;")
    print("  · он подставляет `navigator.languages` из одного тега —")
    print("    порядок предпочтений человека (ru перед en) не проверен;")
    print("  · он исполняет скрипт в node, а не в Safari: `location.replace`")
    print("    здесь не навигация, а запись в переменную.")
    return 1 if находки else 0


if __name__ == "__main__":
    sys.exit(main())
