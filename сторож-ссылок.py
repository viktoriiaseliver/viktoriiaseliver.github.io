#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сторож ссылок: каждая ссылка внутрь сайта обязана вести в файл,
который на этом сайте лежит.

ПОВОД. Замер 23.10.2026. Подвал каждой правовой страницы Того ведёт
на хаб «другие приложения» — `../../<язык>/index.html`. Адрес
собирается в `Togo/Tools/build_site.py:270` по списку `LANGS`, а сами
страницы хаба (`site/<язык>/index.html`) живут в ЭТОМ репозитории и
генератору не принадлежат. Два списка в двух репозиториях, и ни один
не знает о другом: пока в `LANGS` стоял `uk` и `fr`, а хаб был только
на `en` и `ru`, украинец и француз, нажав в подвале «інші застосунки»,
получали 404 на живом сайте.

Дыру закрыли, заведя хаб на пяти языках (`971630f`, `d252ee8`), и
замер после починки дал ноль битых из 793. Но починка не мешает
дыре открыться снова: шестой язык в `LANGS` ПОЯВИТСЯ в подвале сразу
и в хабе — только если кто-то вспомнит. Поэтому рядом с числом
положен инструмент, который это число пересчитывает.

ПОЧЕМУ ОТДЕЛЬНЫЙ СТОРОЖ, А НЕ ПРОВЕРКА В `build_site.py`. Генератор
пишет в `Togo/site/`, а публикация кладёт это в `site/togo/`
(`publish_site.sh:41`). Ссылка `../../<язык>/index.html` в дереве
генератора не разрешается ВОВСЕ — она верна только после переезда.
То есть обе половины встречаются здесь и больше нигде, и спросить
«ведёт ли ссылка в файл» можно только в опубликованном дереве.

ЧЕМ ОТЛИЧАЕТСЯ ОТ СОСЕДА. `сторож-развилок.py` исполняет скрипт
развилки и смотрит, КУДА УВОДИТ язык; этот читает разметку и смотрит,
ЕСТЬ ЛИ ФАЙЛ по адресу. Сосед не видит ссылки в теле страницы, этот
не видит ссылок, которые собирает JavaScript. Вместе они накрывают
обе половины, порознь — ни одной целиком.

    python3 сторож-ссылок.py          # код 0 — битых ссылок нет
"""

from __future__ import annotations

import os
import pathlib
import re
import sys
from urllib.parse import unquote, urlparse

КОРЕНЬ = pathlib.Path(__file__).resolve().parent
ДОМЕН = "https://viktoriiaseliver.github.io"

# Папки, находки по которым НЕ красят код возврата — по решению
# Виктории от 05.10.2026 (`till` игнорируется так же, как Kvit),
# повторённому здесь, а не унаследованному молча.
#
# Список именованный, а не вычищенная проверка, и находки по нему
# ПЕЧАТАЮТСЯ: молча снятая проверка неотличима от проверки, которой
# не было. Разница с соседом нарочная — он о `till` не печатает ни
# строки требований, потому что требование читается как наряд;
# битая ссылка нарядом не читается, она читается как факт.
ИГНОР = ("till",)

# Схемы, которые уводят с сайта: их проверка — это сеть, а не диск,
# и ответ у неё другого рода. Названы поимённо, чтобы «не проверено»
# не слилось с «проверено и цело».
ВНЕШНИЕ = ("http", "https", "mailto", "tel", "data", "javascript")

ССЫЛКА = re.compile(r'(?:href|src)\s*=\s*"([^"]+)"')


def под_игнором(относительный):
    return относительный.split(os.sep)[0] in ИГНОР


def цель(страница, адрес):
    """Куда ведёт адрес — путём на диске, или None, если наружу."""
    разбор = urlparse(адрес)
    if разбор.scheme in ВНЕШНИЕ:
        # Абсолютная ссылка на свой же домен — это тот же сайт,
        # записанный длинно. Их 708, и они несут canonical
        # и hreflang, то есть именно те адреса, которые читает
        # поисковик и App Review.
        if адрес.startswith(ДОМЕН):
            путь = unquote(urlparse(адрес).path).lstrip("/")
            return КОРЕНЬ / путь if путь else КОРЕНЬ / "index.html"
        return None
    if not разбор.path:
        return None  # чистый «#якорь» — проверка якорей этому не по уму
    return (страница.parent / unquote(разбор.path)).resolve()


def разрешить(путь):
    """Папка отдаётся как `index.html` — так её отдаёт и GitHub Pages."""
    if путь.is_dir():
        return путь / "index.html"
    return путь


def main():
    всего = 0
    находки = []
    игнор_находки = []

    страницы = sorted(p for p in КОРЕНЬ.rglob("*.html")
                      if ".git" not in p.parts)

    for страница in страницы:
        текст = страница.read_text(encoding="utf-8")
        относительный = str(страница.relative_to(КОРЕНЬ))
        for адрес in ССЫЛКА.findall(текст):
            путь = цель(страница, адрес)
            if путь is None:
                continue
            всего += 1
            if not разрешить(путь).exists():
                куда = os.path.relpath(разрешить(путь), КОРЕНЬ)
                запись = (относительный, адрес, куда)
                if под_игнором(относительный):
                    игнор_находки.append(запись)
                else:
                    находки.append(запись)

    print(f"страниц прочитано: {len(страницы)}")
    print(f"ссылок внутрь сайта проверено: {всего}")
    print(f"битых: {len(находки)}")
    for где, адрес, куда in находки:
        print(f"  ✗ {где}")
        print(f"      ссылка: {адрес}")
        print(f"      файла нет: {куда}")

    if игнор_находки:
        print()
        print(f"В ИГНОРЕ ({', '.join(ИГНОР)}) — найдено "
              f"{len(игнор_находки)}, код возврата не красят:")
        for где, адрес, куда in игнор_находки:
            print(f"  · {где} → {адрес} (нет: {куда})")

    print()
    print("Границы этого сторожа. У каждой названо, что её снимет —")
    print("иначе граница живёт дольше причины и читается в пользу")
    print("бездействия:")
    print("  · он спрашивает ДИСК, а не выданную страницу: GitHub Pages")
    print("    различает регистр имени, а macOS нет, и `Privacy.html`")
    print("    здесь найдётся, а там отдаст 404.")
    print("    СНИМЕТ: `curl -o /dev/null -w '%{http_code}'` по списку")
    print("    адресов опубликованного сайта — это другой замер,")
    print("    внешняя система, и делать его надо после публикации;")
    print("  · он не проверяет якоря (`#раздел`): адрес до решётки")
    print("    разрешается, элемента с таким `id` может не быть.")
    print("    СНИМЕТ: разбор `id=` на целевой странице — дёшево,")
    print("    но сегодня якорей внутри сайта нет ни одного;")
    print("  · он не ходит по внешним ссылкам вовсе"
          f" ({'/'.join(ВНЕШНИЕ[:3])}…).")
    print("    СНИМЕТ: сеть. Почта при этом проверяется в другом месте —")
    print("    `build_site.py` падает на битом `mailto:` до записи;")
    print("  · он читает разметку регулярным выражением и поэтому НЕ")
    print("    ВИДИТ ссылок, которые собирает JavaScript, — а развилки")
    print("    собраны именно так.")
    print("    СНЯТО СОСЕДОМ: `сторож-развилок.py` исполняет их в node")
    print("    и смотрит, куда язык приезжает. Запускать оба.")
    return 1 if находки else 0


if __name__ == "__main__":
    sys.exit(main())
